"""Export the data behind every paper figure to CSV, and generate the LaTeX figures.

Stage 1 writes tex/data/*.csv, one file per plot panel or per map cell, each with a header
row and one column per series. Every metric comes from results/fleet_main_metrics.json,
the file verify_sec4.py checks the text against, so a figure and the sentence citing it
are read off the same numbers. Fig. 2 also needs the routings themselves, which the
metrics file does not carry; those come from results/fleet_main.jsonl through the same
loader figures.py uses, and the leg counts through figures._leg_usage, so the map is the
one the matplotlib version drew.

Stage 2 writes tex/figs/*.tex: pgfplots and TikZ pictures that read those CSVs at compile
time. Colours, markers and the line-width rule are imported from figures.py, so the
condition -> colour mapping cannot drift between the two renderers.

Only N <= 24 is exported: the paper reports the ladder to N = 24.

usage: python export_plot_data.py
"""
import io
import json
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
os.chdir(HERE)                 # figures.MAIN_FILES is relative to the harness

import figures as F            # colours, markers, the leg-usage rule: one definition
import metrics as MX
import payload as P

TEX = os.path.normpath(os.path.join(HERE, "..", "tex"))
DATA = os.path.join(TEX, "data")
FIGS = os.path.join(TEX, "figs")
METRICS = os.path.join(HERE, "results", "fleet_main_metrics.json")

LADDER = (6, 8, 14, 16, 22, 24)
GRID_N = (8, 16, 24)
CONDS = list(F.CONDITIONS)     # the five principles, then the baseline
PRINCIPLES = list(F.ORDER)
TIERS = (45, 55, 65)
NAN = float("nan")

HEADER = "% Generated by harness/export_plot_data.py from tex/data/*.csv. Do not edit.\n"

# matplotlib marker -> pgfplots mark, filled (proven) and hollow (verified feasible)
PGF_MARK = {"o": ("*", "o", ""), "s": ("square*", "square", ""),
            "^": ("triangle*", "triangle", ""), "D": ("diamond*", "diamond", ""),
            "v": ("triangle*", "triangle", "rotate=180"), "x": ("x", "x", "")}

# Columns are the metric families Sec. IV reports: congestion | travel time | noise.
PANELS = [
    ("max_count",             "max aircraft per tile",      True),
    ("extra_vs_baseline",     "extra fleet-hops",           False),
    ("peak_added",            "peak added noise (dB)",      True),
    ("shared_tile_timesteps", "shared tile-timesteps",      True),
    ("departure_delay_total", "departure delay (ac-steps)", True),
    ("total_added",           "summed added noise (dB)",    True),
]


# ------------------------------------------------------------------ helpers
def load_metrics():
    recs = json.load(io.open(METRICS, encoding="utf-8"))
    I = {(m["condition"], m["N"]): m for m in recs
         if not m.get("probe") and m["N"] in LADDER}
    missing = [(c, n) for c in CONDS for n in LADDER if (c, n) not in I]
    if missing:
        raise SystemExit(f"cells missing from {METRICS}: {missing}")
    return I


def cell(v):
    if v is None or (isinstance(v, float) and math.isnan(v)):
        return "nan"
    if isinstance(v, str):
        return v
    return f"{float(v):.6g}"


def write_csv(name, header, rows):
    os.makedirs(DATA, exist_ok=True)
    with io.open(os.path.join(DATA, name), "w", encoding="utf-8", newline="\n") as f:
        f.write(",".join(header) + "\n")
        for r in rows:
            f.write(",".join(cell(v) for v in r) + "\n")


def write_tex(name, body):
    os.makedirs(FIGS, exist_ok=True)
    with io.open(os.path.join(FIGS, name), "w", encoding="utf-8", newline="\n") as f:
        f.write(HEADER + body)


def proven(m):
    return m.get("optimality") == "optimal"


def series(I, field, conds):
    """One row per N; per condition: mean, band low, band high (proven cells), and the
    value of a verified feasible cell in `_open` (NaN when proven)."""
    header = ["N"] + [f"{c}{s}" for c in conds for s in ("", "_lo", "_hi", "_open")]
    rows = []
    for n in LADDER:
        row = [n]
        for c in conds:
            m = I[(c, n)]
            v = m.get(field)
            lo, hi = m.get(field + "_min", v), m.get(field + "_max", v)
            row += [v, lo, hi, NAN] if proven(m) else [NAN, NAN, NAN, v]
        rows.append(row)
    return header, rows


def col(header, rows, name):
    j = header.index(name)
    return [r[j] for r in rows]


def finite(xs):
    return [x for x in xs if isinstance(x, (int, float)) and not math.isnan(x)]


def has_band(header, rows, c):
    return any(h > l for l, h in zip(col(header, rows, c + "_lo"),
                                     col(header, rows, c + "_hi"))
               if not (math.isnan(l) or math.isnan(h)))


def has_open(header, rows, c):
    return bool(finite(col(header, rows, c + "_open")))


# ------------------------------------------------------------ stage 1: data
def export_metric_panels(I):
    out = {}
    for field, _lab, with_base in PANELS:
        conds = CONDS if with_base else PRINCIPLES
        h, r = series(I, field, conds)
        write_csv(f"mvn_{field}.csv", h, r)
        out[field] = (h, r, conds)
    return out


def export_solve_time(I):
    h, r = series(I, "wall", CONDS)
    write_csv("solve_time.csv", h, r)
    return h, r


def export_capacity(I):
    """Capacity against D from the closed form, the rule fig_capacity uses, checked
    against the capacity the solver recorded for every principle cell at D = 6."""
    alpha = P.AIRCRAFT_DB

    def cap(D, b):
        return max(0, math.floor((10 ** (D / 10) - 1) / 10 ** ((alpha - b) / 10)))

    for (c, n), m in I.items():
        if c == "baseline":
            continue
        want = {str(b): cap(float(m["D"]), b) for b in TIERS}
        got = {str(k): v for k, v in (m.get("tile_capacity") or {}).items()}
        if want != got:
            raise SystemExit(f"closed-form capacity {want} != recorded {got} at {c} N={n}")
    Ds = [x / 10 for x in range(5, 151)]
    write_csv("capacity.csv", ["D"] + [f"cap{b}" for b in TIERS],
              [[D] + [cap(D, b) for b in TIERS] for D in Ds])


def export_routes(I):
    cells, _mets, setup = F._fleet()
    prot = next(m.get("protected_stations") for m in I.values()
                if m.get("protected_stations"))
    ambient = None
    panels = []
    for n in GRID_N:
        for c in CONDS:
            row = cells.get((setup, c, n))
            if row is None:
                raise SystemExit(f"no routing on disk for {c} N={n}")
            req = MX._req_for(row)
            if ambient is None:
                ambient = list(req["baseline"])
            elif list(req["baseline"]) != ambient:
                raise SystemExit("ambient map differs between cells")
            use = F._leg_usage(row, req)
            if not use:
                raise SystemExit(f"no legs flown for {c} N={n}")
            legs = []
            for (a, b), k in sorted(use.items()):
                ra, ca = divmod(a, 5)
                rb, cb = divmod(b, 5)
                legs.append([ra, ca, rb, cb, k])
            write_csv(f"routes_N{n}_{c}.csv", ["r1", "c1", "r2", "c2", "aircraft"], legs)
            m = I[(c, n)]
            panels.append([n, c, m["peak_added"], m["extra_vs_floor"],
                           1 if proven(m) else 0, max(use.values()),
                           str(row.get("key", "")).split("|")[-1]])
    write_csv("routes_panels.csv",
              ["N", "condition", "peak", "hops", "proven", "legmax", "ordering"], panels)
    ports = set(P.vertiport_indices())
    write_csv("routes_tiles.csv", ["station", "row", "col", "ambient", "vertiport",
                                   "protected"],
              [[m + 1, m // 5, m % 5, ambient[m], int(m in ports), int((m + 1) in prot)]
               for m in range(P.M)])
    return panels, sorted(prot)


# ----------------------------------------------------------- stage 2: LaTeX
def _hex(c):
    return c.lstrip("#").upper()


def style_tex():
    lines = []
    for c in CONDS:
        lines.append(rf"\definecolor{{fig-{c}}}{{HTML}}{{{_hex(F.CCOLOR[c])}}}")
    for b in TIERS:
        lines.append(rf"\definecolor{{fig-amb{b}}}{{HTML}}{{{_hex(F.SHADE[b])}}}")
    lines += [r"\definecolor{fig-route}{HTML}{B3261E}",
              rf"\definecolor{{fig-prot}}{{HTML}}{{{_hex(F.PROT_EC)}}}",
              r"\definecolor{fig-t45}{HTML}{1F77B4}",
              r"\definecolor{fig-t55}{HTML}{FF7F0E}",
              r"\definecolor{fig-t65}{HTML}{2CA02C}",
              r"\pgfplotsset{",
              r"  paperaxis/.style={scale only axis, axis lines*=left,",
              r"    font=\footnotesize, tick label style={font=\footnotesize},",
              r"    label style={font=\footnotesize}, tick align=outside,",
              r"    tick style={black!70}, unbounded coords=jump,",
              r"    legend style={font=\footnotesize, draw=none, fill=none},",
              r"    legend cell align=left},",
              r"}"]
    write_tex("style.tex", "\n".join(lines) + "\n")


def _plot_lines(csv, header, rows, conds, tag, legend):
    """Bands first, then one line per condition, then any verified-feasible markers."""
    out = []
    for c in conds:
        if not has_band(header, rows, c):
            continue
        out += [rf"\addplot[name path={tag}{c}hi, draw=none, forget plot] "
                rf"table[x=N, y={c}_hi, col sep=comma] {{{csv}}};",
                rf"\addplot[name path={tag}{c}lo, draw=none, forget plot] "
                rf"table[x=N, y={c}_lo, col sep=comma] {{{csv}}};",
                rf"\addplot[fig-{c}, fill opacity=0.16, draw=none, forget plot] "
                rf"fill between[of={tag}{c}hi and {tag}{c}lo];"]
    for c in conds:
        full, hollow, rot = PGF_MARK[F.CMARK[c]]
        mo = ", ".join(x for x in ("solid", f"fill=fig-{c}", rot) if x)
        dash = ", dashed" if c == "baseline" else ""
        out.append(rf"\addplot[fig-{c}, line width=0.8pt{dash}, mark={full}, "
                   rf"mark size=1.6pt, mark options={{{mo}}}] "
                   rf"table[x=N, y={c}, col sep=comma] {{{csv}}};")
        if legend:
            out.append(rf"\addlegendentry{{{F.CLABEL[c]}}}")
        if has_open(header, rows, c):
            mo = ", ".join(x for x in ("solid", "fill=white", rot) if x)
            out.append(rf"\addplot[fig-{c}, only marks, mark={hollow}, mark size=1.6pt, "
                       rf"mark options={{{mo}}}, forget plot] "
                       rf"table[x=N, y={c}_open, col sep=comma] {{{csv}}};")
    return out


VLINE = (r"\draw[black!18, line width=0.5pt] ({axis cs:16,1}|-{rel axis cs:0,0}) "
         r"-- ({axis cs:16,1}|-{rel axis cs:0,1});")
XTICKS = "xmin=4.8, xmax=25.2, xtick={6,8,14,16,22,24}"


def metric_vs_N_tex(panels):
    L = [r"\begin{tikzpicture}",
         r"\begin{groupplot}[group style={group size=3 by 2, horizontal sep=0.60in,",
         r"    vertical sep=0.30in}, paperaxis, width=1.72in, height=0.95in,",
         rf"    {XTICKS}]"]
    for i, (field, ylab, _wb) in enumerate(PANELS):
        h, r, conds = panels[field]
        opts = [f"ylabel={{{ylab}}}"]
        if i >= 3:
            opts.append(r"xlabel={fleet size $N$}")
        if i == 0:
            opts += [r"legend to name=mvnlegend", "legend columns=6",
                     r"legend style={/tikz/every even column/.append style="
                     r"{column sep=6pt}}"]
        L.append(r"\nextgroupplot[" + ", ".join(opts) + "]")
        csv = f"data/mvn_{field}.csv"
        L += _plot_lines(csv, h, r, conds, f"p{i}", legend=(i == 0))
        L.append(VLINE)
        if field == "extra_vs_baseline":
            L.append(r"\draw[black!45, dashed, line width=0.5pt] "
                     r"({rel axis cs:0,0}|-{axis cs:6,0}) -- ({rel axis cs:1,0}|-{axis cs:6,0});")
    L += [r"\end{groupplot}",
          r"\node[anchor=north] at ($(group c2r2.south)+(0,-0.36in)$) "
          r"{\pgfplotslegendfromname{mvnlegend}};",
          r"\end{tikzpicture}"]
    write_tex("metric_vs_N.tex", "\n".join(L) + "\n")


def solve_time_tex(h, r):
    L = [r"\begin{tikzpicture}",
         r"\begin{axis}[paperaxis, width=2.55in, height=1.45in, ymode=log,",
         rf"    {XTICKS}, xlabel={{fleet size $N$}}, ylabel={{solve time (s)}},",
         r"    legend columns=3, legend style={at={(0.5,-0.36)}, anchor=north,",
         r"    /tikz/every even column/.append style={column sep=5pt}}]"]
    L += _plot_lines("data/solve_time.csv", h, r, CONDS, "st", legend=True)
    L.append(VLINE)
    L += [r"\end{axis}", r"\end{tikzpicture}"]
    write_tex("solve_time.tex", "\n".join(L) + "\n")


def capacity_tex():
    csv = "data/capacity.csv"
    alpha = P.AIRCRAFT_DB

    def cap(D, b):
        return max(0, math.floor((10 ** (D / 10) - 1) / 10 ** ((alpha - b) / 10)))

    L = [r"\begin{tikzpicture}",
         r"\begin{axis}[paperaxis, width=2.65in, height=1.30in, ymode=log,",
         r"    log ticks with fixed point, ytick={1,10,100,1000},",
         r"    xmin=0.5, xmax=15, ymin=0.3, ymax=5000, xtick={2,4,6,8,10,12,14},",
         r"    xlabel={cap $D$ (dB of added noise)}, ylabel={aircraft per tile}]",
         r"\fill[black!8] (axis cs:0.5,0.3) rectangle (axis cs:15,0.55);",
         r"\node[anchor=east, black!60] at (axis cs:14.8,0.41) {capacity 0};",
         r"\draw[black!35, line width=0.4pt] (axis cs:0.5,1) -- (axis cs:15,1);"]
    for b, dash in ((45, "solid"), (55, "dashed"), (65, "densely dotted")):
        L.append(rf"\addplot[const plot, fig-t{b}, line width=1pt, {dash}] "
                 rf"table[x=D, y expr={{max(\thisrow{{cap{b}}},0.4)}}, col sep=comma] {{{csv}}};")
    # Each curve is labelled just below-right of its own value at D = 9.6: the curves
    # rise to the right, so that corner is clear. A legend box covered the 65 dBA line.
    for b in TIERS:
        L.append(rf"\node[anchor=north west, inner sep=1pt, text=fig-t{b}] "
                 rf"at (axis cs:9.6,{cap(9.6, b)}) {{{b}\,dBA}};")
    L += [r"\end{axis}", r"\end{tikzpicture}"]
    write_tex("capacity.tex", "\n".join(L) + "\n")


def routes_grid_tex(panels, prot):
    """Every scratch macro is prefixed \\rt: a bare \\k or \\aa would shadow LaTeX's
    accent commands inside the loop body."""
    PX, PY, U = 5.55, 6.15, "0.2in"
    idx = {(p[0], p[1]): i for i, p in enumerate(panels)}
    L = [r"\pgfplotstableread[col sep=comma]{data/routes_tiles.csv}\routestiles",
         r"\pgfplotstableread[col sep=comma]{data/routes_panels.csv}\routespanels",
         # tiles shaded by ambient tier, then the protected outline (zorder 0 and 2)
         r"\def\routesbase{%",
         r"  \pgfplotstablegetrowsof{\routestiles}%",
         r"  \pgfmathtruncatemacro\routesnt{\pgfplotsretval-1}%",
         r"  \foreach \rtK in {0,...,\routesnt}{%",
         r"    \pgfplotstablegetelem{\rtK}{row}\of\routestiles\edef\rtRow{\pgfplotsretval}%",
         r"    \pgfplotstablegetelem{\rtK}{col}\of\routestiles\edef\rtCol{\pgfplotsretval}%",
         r"    \pgfplotstablegetelem{\rtK}{ambient}\of\routestiles\edef\rtAmb{\pgfplotsretval}%",
         r"    \fill[fig-amb\rtAmb] (\rtCol-0.5,-\rtRow-0.5) rectangle ++(1,1);",
         r"    \draw[white, line width=0.7pt] (\rtCol-0.5,-\rtRow-0.5) rectangle ++(1,1);",
         r"  }%",
         r"  \foreach \rtK in {0,...,\routesnt}{%",
         r"    \pgfplotstablegetelem{\rtK}{protected}\of\routestiles\edef\rtProt{\pgfplotsretval}%",
         r"    \ifnum\rtProt=1",
         r"      \pgfplotstablegetelem{\rtK}{row}\of\routestiles\edef\rtRow{\pgfplotsretval}%",
         r"      \pgfplotstablegetelem{\rtK}{col}\of\routestiles\edef\rtCol{\pgfplotsretval}%",
         r"      \draw[fig-prot, line width=0.8pt, dash pattern=on 1.8pt off 1.1pt]",
         r"        (\rtCol-0.45,-\rtRow-0.45) rectangle ++(0.9,0.9);",
         r"    \fi",
         r"  }%",
         r"}",
         # vertiports ringed, on top of the legs (zorder 4)
         r"\def\routesports{%",
         r"  \foreach \rtK in {0,...,\routesnt}{%",
         r"    \pgfplotstablegetelem{\rtK}{vertiport}\of\routestiles\edef\rtPort{\pgfplotsretval}%",
         r"    \ifnum\rtPort=1",
         r"      \pgfplotstablegetelem{\rtK}{row}\of\routestiles\edef\rtRow{\pgfplotsretval}%",
         r"      \pgfplotstablegetelem{\rtK}{col}\of\routestiles\edef\rtCol{\pgfplotsretval}%",
         r"      \draw[black!87, line width=0.9pt] (\rtCol,-\rtRow) circle (0.21);",
         r"    \fi",
         r"  }%",
         r"}",
         # each leg: width 0.7 + 2.6 n / n_max pt, the rule figures._draw_map uses
         r"\def\routeslegs#1#2{%",
         r"  \pgfplotstablegetrowsof{#1}%",
         r"  \pgfmathtruncatemacro\routesnl{\pgfplotsretval-1}%",
         r"  \foreach \rtK in {0,...,\routesnl}{%",
         r"    \pgfplotstablegetelem{\rtK}{r1}\of#1\edef\rtRa{\pgfplotsretval}%",
         r"    \pgfplotstablegetelem{\rtK}{c1}\of#1\edef\rtCa{\pgfplotsretval}%",
         r"    \pgfplotstablegetelem{\rtK}{r2}\of#1\edef\rtRb{\pgfplotsretval}%",
         r"    \pgfplotstablegetelem{\rtK}{c2}\of#1\edef\rtCb{\pgfplotsretval}%",
         r"    \pgfplotstablegetelem{\rtK}{aircraft}\of#1\edef\rtNum{\pgfplotsretval}%",
         r"    \pgfmathsetmacro\rtWid{0.7+2.6*\rtNum/#2}%",
         r"    \draw[fig-route, draw opacity=0.8, line cap=round, line width=\rtWid pt]",
         r"      (\rtCa,-\rtRa) -- (\rtCb,-\rtRb);",
         r"  }%",
         r"}",
         r"\def\routestitle#1{%",
         r"  \pgfplotstablegetelem{#1}{peak}\of\routespanels\edef\rtPeak{\pgfplotsretval}%",
         r"  \pgfplotstablegetelem{#1}{hops}\of\routespanels\edef\rtHops{\pgfplotsretval}%",
         r"  \pgfplotstablegetelem{#1}{proven}\of\routespanels\edef\rtProv{\pgfplotsretval}%",
         r"  \pgfmathprintnumber[fixed,fixed zerofill,precision=2]{\rtPeak}\,dB,",
         r"  +\pgfmathprintnumber[fixed,precision=2]{\rtHops}~hops\ifnum\rtProv=0 $^\dagger$\fi}",
         rf"\begin{{tikzpicture}}[x={U}, y={U}, font=\footnotesize]"]
    for ci, c in enumerate(CONDS):
        L.append(rf"\node[anchor=base] at ({ci * PX + 2:.2f},1.55) {{{F.CLABEL[c]}}};")
    for ri, n in enumerate(GRID_N):
        L.append(rf"\node[rotate=90, anchor=center] at (-1.05,{-2 - ri * PY:.2f}) {{$N={n}$}};")
        for ci, c in enumerate(CONDS):
            i = idx[(n, c)]
            L += [rf"\begin{{scope}}[shift={{({ci * PX:.2f},{-ri * PY:.2f})}}]",
                  r"  \routesbase",
                  rf"  \pgfplotstableread[col sep=comma]{{data/routes_N{n}_{c}.csv}}\routeslegtab",
                  rf"  \pgfplotstablegetelem{{{i}}}{{legmax}}\of\routespanels\edef\rtMax{{\pgfplotsretval}}",
                  r"  \routeslegs{\routeslegtab}{\rtMax}",
                  r"  \routesports",
                  rf"  \node[anchor=base] at (2,0.72) {{\routestitle{{{i}}}}};",
                  r"\end{scope}"]
    # one legend under the grid, centred on it
    y = -(len(GRID_N) - 1) * PY - 5.35
    x = 3 * PX - 9.3
    items = []
    for b in TIERS:
        items.append((rf"\fill[fig-amb{b}] ({{X}},{y:.2f}) rectangle ++(0.7,0.5);",
                      rf"{b}\,dBA", 3.0 if b < 65 else 3.4))
    items.append((rf"\draw[fig-prot, line width=0.8pt, dash pattern=on 1.8pt off 1.1pt] "
                  rf"({{X}},{y:.2f}) rectangle ++(0.7,0.5);",
                  "protected: stations " + ", ".join(str(s) for s in prot), 0))
    for draw, label, step in items:
        L.append(draw.replace("{X}", f"{x:.2f}"))
        L.append(rf"\node[anchor=west] at ({x + 0.8:.2f},{y + 0.25:.2f}) {{{label}}};")
        x += step
    L.append(r"\end{tikzpicture}")
    write_tex("routes_grid.tex", "\n".join(L) + "\n")


def main():
    I = load_metrics()
    panels = export_metric_panels(I)
    st = export_solve_time(I)
    export_capacity(I)
    rp, prot = export_routes(I)
    style_tex()
    metric_vs_N_tex(panels)
    solve_time_tex(*st)
    capacity_tex()
    routes_grid_tex(rp, prot)
    n_csv = len([f for f in os.listdir(DATA) if f.endswith(".csv")])
    print(f"wrote {n_csv} CSVs to {os.path.relpath(DATA, HERE)} and 5 .tex files to "
          f"{os.path.relpath(FIGS, HERE)} (N <= {max(LADDER)})")


if __name__ == "__main__":
    main()
