"""Export the data behind every paper figure to CSV, and generate the LaTeX figures.

Stage 1 writes tex/data/*.csv, one file per plot panel or per map cell, each with a header
row and one column per series. Every metric comes from results/fleet_main_metrics.json,
the file verify_sec4.py checks the text against, so a figure and the sentence citing it
are read off the same numbers. Fig. 2 also needs the routings themselves, which the
metrics file does not carry; those come from results/fleet_main.jsonl through the same
loader figures.py uses, and the leg counts through figures._leg_usage, so the map is the
one the matplotlib version drew.

Stage 2 writes tex/figs/*.tex: pgfplots and TikZ pictures that read those CSVs at compile
time. Colours, markers and the line-width rule are imported from figures.py, so the
condition -> colour mapping cannot drift between the two renderers.

Only N <= 24 is exported: the paper reports the ladder to N = 24.

usage: python export_plot_data.py
"""
