def load_metrics():
    recs = json.load(io.open(METRICS, encoding="utf-8"))
    I = {(m["condition"], m["N"]): m for m in recs
         if not m.get("probe") and m["N"] in LADDER}
    missing = [(c, n) for c in CONDS for n in LADDER if (c, n) not in I]
    if missing:
        raise SystemExit(f"cells missing from {METRICS}: {missing}")
    # Decibel-form cells (encoding.py builds them through the same metrics pipeline,
    # joined to the ladder's baseline). A cell the sweep never reached is simply absent.
    if os.path.exists(DB_METRICS):
        for m in json.load(io.open(DB_METRICS, encoding="utf-8")):
            if m.get("condition") in DBF.values() and m.get("N") in LADDER:
                I[(m["condition"], m["N"])] = m
    # Departure hold: aircraft-timesteps held beyond the fleet's own size. The raw total
    # is N + hold, so every condition sits on one diagonal and the difference between
    # them is invisible; the hold is what the objectives actually pay.
    for (c, n), m in I.items():
        for suf in ("", "_min", "_max"):
            v = m.get("departure_delay_total" + suf)
            if v is not None:
                m["departure_hold" + suf] = v - n
    return I


def cell(v):
    if v is None or (isinstance(v, float) and math.isnan(v)):
        return "nan"
    if isinstance(v, str):
        return v
    return f"{float(v):.6g}"


def write_csv(name, header, rows):
    os.makedirs(DATA, exist_ok=True)
    with io.open(os.path.join(DATA, name), "w", encoding="utf-8", newline="\n") as f:
        f.write(",".join(header) + "\n")
        for r in rows:
            f.write(",".join(cell(v) for v in r) + "\n")


def write_tex(name, body):
    os.makedirs(FIGS, exist_ok=True)
    with io.open(os.path.join(FIGS, name), "w", encoding="utf-8", newline="\n") as f:
        f.write(HEADER + body)


def proven(m):
    # All four orderings: a decibel cell with fewer runs has no band, and aggregate()
    # would otherwise call a one-run cell "optimal" and plot it as a filled, band-free mean.
    return m.get("optimality") == "optimal" and m.get("runs", 4) == 4


def series(I, field, conds, open_mode="all"):
    """One row per N; per condition: mean, band low, band high (proven cells), and the
    value of a verified feasible cell in `_open` (NaN when proven)."""
    header = ["N"] + [f"{c}{s}" for c in conds for s in ("", "_lo", "_hi", "_open")]
    rows = []
    for n in LADDER:
        row = [n]
        for c in conds:
            m = I.get((c, n))
            if m is None:                 # a decibel cell the sweep never reached
                row += [NAN] * 4
                continue
            v = m.get(field)
            lo, hi = m.get(field + "_min", v), m.get(field + "_max", v)
            if proven(m):
                row += [v, lo, hi, NAN]
            else:
                # A cell where some ordering proved is a real optimum with no band, drawn
                # hollow; a cell where none did is a stopped search and is not plotted.
                show = (open_mode == "all"
                        or (open_mode == "proven" and (m.get("runs_proven") or 0) >= 1))
                row += [NAN, NAN, NAN, v if show else NAN]
        rows.append(row)
    return header, rows


def col(header, rows, name):
    j = header.index(name)
    return [r[j] for r in rows]


def finite(xs):
    return [x for x in xs if isinstance(x, (int, float)) and not math.isnan(x)]


def has_band(header, rows, c):
    return any(h > l for l, h in zip(col(header, rows, c + "_lo"),
                                     col(header, rows, c + "_hi"))
               if not (math.isnan(l) or math.isnan(h)))


def has_open(header, rows, c):
    return bool(finite(col(header, rows, c + "_open")))


# ------------------------------------------------------------ stage 1: data
def export_metric_panels(I):
    out = {}
    for field, _lab, with_base, hollow in PANELS:
        conds = SERIES if with_base else [c for c in SERIES if c != "baseline"]
        h, r = series(I, field, conds, open_mode="proven" if hollow else "none")
        write_csv(f"mvn_{field}.csv", h, r)
        out[field] = (h, r, conds)
    return out


def export_solve_time(I):
    h, r = series(I, "wall", CONDS)
    write_csv("solve_time.csv", h, r)
    return h, r


def export_capacity(I):
    """Capacity against D from the closed form, the rule fig_capacity uses, checked
    against the capacity the solver recorded for every principle cell at D = 6."""
    alpha = P.AIRCRAFT_DB

    def cap(D, b):
        return max(0, math.floor((10 ** (D / 10) - 1) / 10 ** ((alpha - b) / 10)))

    for (c, n), m in I.items():
        if c == "baseline":
            continue
        want = {str(b): cap(float(m["D"]), b) for b in TIERS}
        got = {str(k): v for k, v in (m.get("tile_capacity") or {}).items()}
        if want != got:
            raise SystemExit(f"closed-form capacity {want} != recorded {got} at {c} N={n}")
    Ds = [x / 10 for x in range(5, 151)]
    write_csv("capacity.csv", ["D"] + [f"cap{b}" for b in TIERS],
              [[D] + [cap(D, b) for b in TIERS] for D in Ds])


def _db_rows():
    """Decibel-form routings to draw, keyed (condition, N): the lowest-numbered proven
    ordering, else the lowest-numbered one stopped at the harvest."""
    import metrics_run as MR
    best = {}
    for r in MR.load(["results/fleet_db.jsonl"]):
        if r.get("status") != "sat" or not r.get("paths"):
            continue
        key = (str(r.get("key", "")).split("|")[2], r.get("N"))
        rank = (0 if r.get("optimality") == "optimal" else 1, r.get("perm") or 0)
        if key not in best or rank < best[key][0]:
            best[key] = (rank, r)
    return {k: v[1] for k, v in best.items()}


def export_routes(I):
    """One legs CSV per map. A decibel cell with no proven ordering is a *timeout*: its
    map is the verified routing the search held when the harvest stopped it."""
    cells, _mets, setup = F._fleet()
    dbr = _db_rows()
    prot = next(m.get("protected_stations") for m in I.values()
                if m.get("protected_stations"))
    ambient = None
    panels = []
    for n in GRID_N:
        for c in GRID_ROWS:
            row = dbr.get((c, n)) if c in DBF.values() else cells.get((setup, c, n))
            if row is None:
                raise SystemExit(f"no routing on disk for {c} N={n}")
            req = MX._req_for(row)
            if ambient is None:
                ambient = list(req["baseline"])
            elif list(req["baseline"]) != ambient:
                raise SystemExit("ambient map differs between cells")
            use = F._leg_usage(row, req)
            if not use:
                raise SystemExit(f"no legs flown for {c} N={n}")
            legs = [[a // 5, a % 5, b // 5, b % 5, k] for (a, b), k in sorted(use.items())]
            write_csv(f"routes_N{n}_{c}.csv", ["r1", "c1", "r2", "c2", "aircraft"], legs)
            m = I.get((c, n)) or {}
            timeout = int(c in DBF.values() and m.get("runs_proven", 0) == 0)
            panels.append([n, c, m.get("peak_added"), m.get("extra_vs_floor"),
                           int(proven(m)), max(use.values()),
                           str(row.get("key", "")).split("|")[-1], timeout])
    write_csv("routes_panels.csv",
              ["N", "condition", "peak", "hops", "proven", "legmax", "ordering", "timeout"],
              panels)
    ports = set(P.vertiport_indices())
    write_csv("routes_tiles.csv", ["station", "row", "col", "ambient", "vertiport",
                                   "protected"],
              [[m + 1, m // 5, m % 5, ambient[m], int(m in ports), int((m + 1) in prot)]
               for m in range(P.M)])
    return panels, sorted(prot)


