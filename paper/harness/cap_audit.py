"""Which claims in the paper rest on a run that hit the time budget?

A run's status determines what it can support:

  optimal   proven best for its objective. Safe for any claim.
  partial   objective applied, incumbent verified against every hard constraint, but
            not proven best. Safe for "the principle moved X in this direction" when
            the incumbent ALREADY beats the comparison (the true optimum is at least
            as good). NOT safe for "the optimum is exactly V", nor for orderings
            between principles.
  fallback  phase 2 produced nothing; the served route is phase 1's unweighted one.
            Supports NOTHING about the principle. Must never be compared against a
            row that does.
  infeasible / timeout   no routing at all.

Anything read off the returned ROUTING rather than off the objective -- occupancy,
peak dB, spread, tier share, detour -- is a true property of a real, constraint-
satisfying routing even when that routing is `partial`. Such claims are safe as
statements about "the routing the solver returned", and unsafe only if phrased as
statements about "the optimal routing".

usage: python cap_audit.py        (writes ../results/cap_audit.md)
"""
import glob
import io
import json
import os
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))


# Grade the data the PAPER uses, which means the long-budget merge must be applied
# here too. Auditing the raw rows would report a claim as unsafe long after a
# four-hour re-run had settled it -- and, worse, could pass a claim that the merge
# had since overturned.
import sys
sys.path.insert(0, HERE)
import analyze as A


def rows(name, raw=False):
    if raw:
        p = os.path.join(HERE, "results", name + ".jsonl")
        if not os.path.exists(p):
            return []
        out = []
        for line in io.open(p, encoding="utf-8"):
            try:
                out.append(json.loads(line))
            except Exception:
                pass
        return out
    return A.load(name)


# Single source of truth: analyze.status_mark. A second copy of the grading logic here
# is exactly how the audit and the tables it audits drift apart.
grade = A.status_mark


L = []
L.append("# What the 600 s budget touched")
L.append("")
L.append("Generated by `paper/harness/cap_audit.py`. Every claim in Section IV is listed")
L.append("with the rows that support it and the status of each. Regenerate after any new")
L.append("sweep lands.")
L.append("")

# ---------------------------------------------------------------- global picture
L.append("## Status of every recorded solve")
L.append("")
L.append("| sweep | optimal | partial | fallback | unsettled | killed |")
L.append("|---|---|---|---|---|---|")
allrows = {}
for f in sorted(glob.glob(os.path.join(HERE, "results", "*.jsonl"))):
    name = os.path.basename(f)[:-6]
    rs = rows(name, raw=True)
    allrows[name] = rows(name)
    c = defaultdict(int)
    for r in rs:
        c[grade(r)] += 1
    L.append(f"| {name} | {c['optimal']} | {c['partial']} | {c['fallback']} | "
             f"{c['unsettled']} | {c['killed']} |")
L.append("")

# ---------------------------------------------------------------- per claim
scaling = {(r["cfg"]["principle"], r["cfg"]["demand_factor"]): r
           for r in allrows.get("scaling", [])
           if r["cfg"].get("who", "communities") == "communities"}
ORDER = ["equal", "sufficientarian", "prioritarian", "utilitarian", "proportional"]


def claim(title, verdict, detail):
    L.append(f"### {title}")
    L.append("")
    L.append(f"**{verdict}**")
    L.append("")
    L.extend(detail)
    L.append("")


L.append("## Budget homogeneity")
L.append("")
L.append("Grading by STATUS alone is not sufficient. A table whose rows are all `partial`")
L.append("is still confounded if some were given 600 s and others four hours -- the longer")
L.append("run simply got further. That confound produced two retracted findings (the")
L.append("shortest-path detour comparison and the routing-distinctness table), and neither")
L.append("was caught by the status check. This section exists because of them.")
L.append("")


def budget_of(r):
    return int(r.get("budget_s") or 600)


def homogeneity(name, rows, group):
    """Groups whose UNPROVEN rows were given different budgets.

    A proven-optimal row is unaffected by how much time it was allowed -- more budget
    could not have improved it -- so it is comparable against anything. The confound
    bites only among rows that stopped early: there, the one with the longer budget
    simply got further, and any difference between them may be budget rather than
    principle. Flagging proven rows too would condemn every table in the paper and
    teach the reader nothing.
    """
    buckets = defaultdict(set)
    for r in rows:
        if grade(r) == "optimal":
            continue
        g = group(r)
        if g is not None:
            buckets[g].add(budget_of(r))
    return {g: sorted(b) for g, b in buckets.items() if len(b) > 1}


sc = [r for r in allrows.get("scaling", [])
      if r["cfg"].get("who", "communities") == "communities"]
# A comparison ACROSS principles at one fleet size is confounded if the principles were
# given different budgets there.
per_N = homogeneity("scaling", sc, lambda r: r["N"])
# A comparison ACROSS fleet sizes for one principle is confounded the same way.
per_P = homogeneity("scaling", sc, lambda r: r["cfg"]["principle"])

L.append("| grouping | groups with mixed budgets | verdict |")
L.append("|---|---|---|")
L.append(f"| across principles, at one $N$ | "
         f"{', '.join(f'N={k}: {v}' for k, v in sorted(per_N.items())) or 'none'} | "
         f"{'**CONFOUNDED** -- do not compare principles at these sizes' if per_N else 'safe'} |")
L.append(f"| across $N$, for one principle | "
         f"{', '.join(f'{k}: {v}' for k, v in sorted(per_P.items())) or 'none'} | "
         f"{'**CONFOUNDED** -- do not pool fleet sizes for these principles' if per_P else 'safe'} |")
L.append("")
L.append("Any table that pools rows across a confounded grouping must either restrict to a")
L.append("common budget or report the budget per cell. The detour table did neither and was")
L.append("withdrawn.")
L.append("")

L.append("## Claim-by-claim")
L.append("")

# 1 -- collapse
