# -- machine load, which neither status nor budget can express -------------------
# Phase 1 is budget-independent: it runs to completion or fails, and its wall time
# therefore measures contention rather than search effort. Comparing the same
# configuration across sweeps gives a load ratio. This exists because the long-budget
# re-runs happened to land on a quieter machine, so every 600 s-vs-4 h comparison in
# the paper moves two variables at once.
import statistics
from collections import defaultdict as _dd
_p1 = _dd(lambda: _dd(list))
for _name in sorted(allrows):
    # RAW rows, deliberately. The merged loader replaces a row with the best run of the
    # same configuration, so a merged corpus compares a row against itself and reports
    # a load ratio of 1.0 -- hiding exactly the confound this probe exists to expose.
    for _r in rows(_name, raw=True):
        if _r.get("t_phase1") is None or not _r.get("cfg"):
            continue
        _ck = json.dumps({k: _r["cfg"][k] for k in sorted(_r["cfg"])}, sort_keys=True)
        _p1[_ck][_name].append(_r["t_phase1"])
_ratios = []
for _ck, _sw in _p1.items():
    if len(_sw) < 2:
        continue
    _med = [statistics.median(v) for v in _sw.values() if v]
    if min(_med) > 0:
        _ratios.append(max(_med) / min(_med))
if _ratios:
    claim("Machine load across sweeps",
          (f"CONFOUNDED -- median phase-1 ratio {statistics.median(_ratios):.2f}x "
           f"across sweeps" if statistics.median(_ratios) > 1.5 else "acceptable"),
          [f"{len(_ratios)} configurations were solved in more than one sweep. Phase-1 "
           f"wall time is budget-independent, so its ratio between sweeps measures",
           f"contention alone: median {statistics.median(_ratios):.2f}x, "
           f"max {max(_ratios):.1f}x.",
           "",
           "Consequence: a 600 s row and a four-hour row of the same configuration",
           "differ in BUDGET and in LOAD. Every retraction in this paper rests on such",
           "a pair. The direction of a retraction survives (both changes favour the",
           "long run, and each retraction WITHDRAWS a claimed effect rather than",
           "asserting a new one), but no wall-clock figure is a single-process",
           "measurement and the tractability ordering should be read as ordinal.",
           "This is the one confound the audit can detect but not correct."])

