"""Cross-check Z3's `optimal` verdicts with an independent refutation query.

The paper's central claims are claims about optima -- "both are optimal",
"interchangeable optima", "the arrival penalty is identical". Nothing verified those
verdicts: `_model_is_feasible` checks that an incumbent satisfies the constraints, which
is a different and weaker property.

Exhaustive enumeration is not available: at N=6, T=6 on a 25-tile graph with out-degree
~7 the path space is about 7^30, so brute force is not a option at any fleet size.

What IS available is a refutation. If Z3 reports arrival penalty V as optimal, then
    hard constraints  AND  arrival <= V - 1
must be UNSAT. That is a plain satisfiability query, not an optimisation, so it exercises
a different code path in Z3 (Solver rather than Optimize, no lexicographic machinery)
and would catch a wrong optimality verdict. It shares the solver and the encoding, so it
is a cross-check rather than a fully independent oracle -- stated as such in the paper.

usage: python verify_optimal.py [--max N]     writes ../results/optimality_checks.md
"""
import importlib.util as iu
import io
import json
import os
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import analyze as A
import payload as P

SOLVER = r"d:/Documents/EECS_199_Shoukry/solver_server_dB.py"
spec = iu.spec_from_file_location("SOLVER_DB", SOLVER)
S = iu.module_from_spec(spec)
spec.loader.exec_module(S)
from z3 import And, Bool, If, Implies, Int, Not, Or, Solver, Sum, sat, unsat


def refute(req, T, bound, timeout_s=900):
    """Is there a routing with arrival penalty <= bound? Rebuilds the hard constraints
    only -- the objective is replaced by the bound, which is the whole point."""
    N, M = req["N"], req["M"]
    D_s, U_s = round(req["D"] * S.SCALE), round(req["U"] * S.SCALE)
    mult = [max(1, round(m)) for m in req["aircraftMultipliers"]]
    tbl = S.build_scaled_table(M, sum(mult), req["baseline"], req["aircraftDB"])
    Dc = S._compute_d_counts(M, sum(mult), D_s, tbl)
    adj, sp, ep = req["adjacency"], req["startPositions"], req["endPositions"]

    s = Solver()
    s.set("timeout", timeout_s * 1000)
    L = [[Int(f"L_{i}_{t}") for t in range(T)] for i in range(N)]
    for i in range(N):
        for t in range(T):
            s.add(And(1 <= L[i][t], L[i][t] <= M))
        s.add(L[i][0] == sp[i]); s.add(L[i][T - 1] == ep[i])
        for t in range(T - 1):
            for src in range(1, M + 1):
                d = [x + 1 for x in range(M) if adj[src - 1][x] == 1]
                s.add(Implies(L[i][t] == src, Or([L[i][t + 1] == y for y in d])))
    ha = [[Bool(f"ha_{i}_{t}") for t in range(T)] for i in range(N)]
    mv = [[Bool(f"mv_{i}_{t}") for t in range(T)] for i in range(N)]
    ac = [[Bool(f"ac_{i}_{t}") for t in range(T)] for i in range(N)]
    for i in range(N):
        s.add(ha[i][0] == (L[i][0] == ep[i]))
        s.add(mv[i][0] == False); s.add(ac[i][0] == False)
        for t in range(1, T):
            s.add(ha[i][t] == Or(ha[i][t - 1], L[i][t] == ep[i]))
            s.add(mv[i][t] == Or(mv[i][t - 1], Not(L[i][t] == sp[i])))
            s.add(ac[i][t] == And(mv[i][t], Not(ha[i][t - 1])))
        for t in range(T - 1):
            s.add(Implies(ha[i][t], L[i][t + 1] == ep[i]))
    for t in range(T):
        cnt = [Int(f"c_{m}_{t}") for m in range(M)]
        for m in range(M):
            s.add(cnt[m] == Sum([If(And(L[i][t] == m + 1, ac[i][t]), mult[i], 0)
                                 for i in range(N)]))
            s.add(And(0 <= cnt[m], cnt[m] <= Dc[m]))
        db = [S.make_dB_expr(cnt[m], m, tbl, Dc[m]) for m in range(M)]
        hi, lo = Int(f"hi_{t}"), Int(f"lo_{t}")
        for m in range(M):
            s.add(hi >= db[m]); s.add(lo <= db[m])
        s.add(hi - lo <= U_s)
    s.add(Sum([If(Not(ha[i][t]), 1, 0) for i in range(N) for t in range(T)]) <= bound)
    return str(s.check())


def main():
    lim = 24
    if "--max" in sys.argv:
        lim = int(sys.argv[sys.argv.index("--max") + 1])
    # Only principles whose phase-2 objective is arrival alone: with a live principle
    # term the reported arrival is not the minimised quantity, so "arrival - 1 is
    # unreachable" is not the right refutation.
    targets = []
    for r in A.load("scaling"):
        c = r["cfg"]
        if (c["principle"] in ("equal", "sufficientarian")
                and c.get("who", "communities") == "communities"
                and A.status_mark(r) == "optimal" and r.get("arrivalPenalty")
                and r["N"] <= lim):
            targets.append(r)
    targets.sort(key=lambda r: (r["N"], r["cfg"]["principle"]))

    L = ["# Independent optimality cross-check", "",
         "Generated by `paper/harness/verify_optimal.py`.", "",
         "For each run Z3 reported as `optimal` with claimed arrival penalty $V$, we ask a",
         "separate satisfiability query: do the hard constraints admit any routing with",
         "arrival $\\le V-1$? A correct optimality verdict requires **unsat**. This uses",
         "`Solver` rather than `Optimize` and no lexicographic machinery, so it exercises a",
         "different path -- but the same solver and the same encoding, so it is a",
         "cross-check, not an independent oracle. Exhaustive enumeration is unavailable:",
         "the path space is roughly $7^{30}$ at $N=6$.", "",
         "| principle | N | claimed optimum | query: arrival <= V-1 | verdict | s |",
         "|---|---|---|---|---|---|"]
    bad = 0
    for r in targets:
        c = r["cfg"]
        req = P.build_request(**c)
        T = r.get("T_used") or r.get("T_max_used") or req["T_max"]
        V = r["arrivalPenalty"]
        t0 = time.monotonic()
        res = refute(req, T, V - 1)
        el = time.monotonic() - t0
        ok = res == "unsat"
        if res == "sat":
            bad += 1
        L.append(f"| {A.LABEL[c['principle']]} | {r['N']} | {V} | `{res}` | "
                 f"{'confirmed' if ok else ('**REFUTED**' if res=='sat' else 'inconclusive (timeout)')} "
                 f"| {el:.1f} |")
        print(f"  {c['principle']:16s} N={r['N']:>3} V={V:>4} -> {res} ({el:.1f}s)",
              flush=True)
    L += ["", f"**{len(targets)} verdicts checked, {bad} refuted.**"]
    if bad == 0:
        L.append("")
        L.append("No optimality verdict was contradicted. Note what this does and does not")
        L.append("establish: it confirms that no better routing exists *within this")
        L.append("encoding*. It cannot detect an error shared by the encoding and the")
        L.append("check -- for that an independent model (an ILP, say) would be needed.")
    out = os.path.join(HERE, "..", "results", "optimality_checks.md")
    io.open(out, "w", encoding="utf-8", newline="\n").write("\n".join(L) + "\n")
    print("\nwrote", os.path.normpath(out))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
